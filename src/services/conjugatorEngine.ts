interface VerbPattern {
  form: number; // 1, 2, 3, 4, 5, 6, 7, 8, 10
  c1: string;
  c2: string;
  c3: string;
  isNaqis: boolean; // berakhiran alif/alif maqsura/ya
  pastC2Vowel: 'َ' | 'ِ' | 'ُ';
}

function detectVerbPattern(verb: string): VerbPattern {
  const clean = stripArabicDiacritics(verb).trim();
  const lastChar = clean[clean.length - 1];
  const isNaqis = lastChar === 'ى' || lastChar === 'ي' || lastChar === 'ا';

  // Form X: است... (istaf'ala) misal: استغفر, استخرج
  if (clean.startsWith('است') && clean.length >= 6) {
    return {
      form: 10,
      c1: clean[3],
      c2: clean[4],
      c3: clean[5] || 'ل',
      isNaqis,
      pastC2Vowel: 'َ',
    };
  }

  // Form VII: ان... (infa'ala) misal: انطلق, انكسر
  if (clean.startsWith('ان') && clean.length === 5) {
    return {
      form: 7,
      c1: clean[2],
      c2: clean[3],
      c3: clean[4],
      isNaqis,
      pastC2Vowel: 'َ',
    };
  }

  // Form VIII: ا.ت.. atau إ.ت.. (ifta'ala) misal: ارتدى, اعتبر, اجتمع
  if ((clean.startsWith('ا') || clean.startsWith('إ') || clean.startsWith('أ')) && clean[2] === 'ت' && clean.length >= 5) {
    return {
      form: 8,
      c1: clean[1],
      c2: clean[3],
      c3: clean[4] || 'ل',
      isNaqis,
      pastC2Vowel: 'َ',
    };
  }

  // Form V: تف.. (tafa''ala) misal: تعلم, تقدم
  if (clean.startsWith('ت') && clean.length === 4 && (verb.includes('ّ') || clean.length === 5)) {
    return {
      form: 5,
      c1: clean[1],
      c2: clean[2],
      c3: clean[3] || clean[4],
      isNaqis,
      pastC2Vowel: 'َ',
    };
  }

  // Form VI: تفاع. (tafaa'ala) misal: تقاتل, تعاون
  if (clean.startsWith('ت') && clean[2] === 'ا' && clean.length === 5) {
    return {
      form: 6,
      c1: clean[1],
      c2: clean[3],
      c3: clean[4],
      isNaqis,
      pastC2Vowel: 'َ',
    };
  }

  // Form IV: أف.. / اف.. (af'ala) misal: أكرم, أحسن
  if ((clean.startsWith('أ') || clean.startsWith('ا') || clean.startsWith('إ')) && clean.length === 4) {
    return {
      form: 4,
      c1: clean[1],
      c2: clean[2],
      c3: clean[3],
      isNaqis,
      pastC2Vowel: 'َ',
    };
  }

  // Form III: فاع. (faa'ala) misal: قاتل, شارك
  if (clean[1] === 'ا' && clean.length === 4) {
    return {
      form: 3,
      c1: clean[0],
      c2: clean[2],
      c3: clean[3],
      isNaqis,
      pastC2Vowel: 'َ',
    };
  }

  // Form II: فعّل (fa''ala) misal: علّم, قدّم
  if (verb.includes('ّ') && clean.length === 3) {
    return {
      form: 2,
      c1: clean[0],
      c2: clean[1],
      c3: clean[2],
      isNaqis,
      pastC2Vowel: 'َ',
    };
  }

  // Form I (Tsulatsi Mujarrad)
  const c1 = clean[0] || 'ف';
  const c2 = clean[1] || 'ع';
  const c3 = clean[2] || 'ل';

  let pastC2Vowel: 'َ' | 'ِ' | 'ُ' = 'َ';
  if (verb.includes('ِ') || verb.includes(c2 + 'ِ')) {
    pastC2Vowel = 'ِ';
  } else if (verb.includes('ُ') || verb.includes(c2 + 'ُ')) {
    pastC2Vowel = 'ُ';
  }

  return {
    form: 1,
    c1,
    c2,
    c3,
    isNaqis,
    pastC2Vowel,
  };
}

function getFutureVowel(futureType: FutureType): 'َ' | 'ُ' | 'ِ' {
  if (futureType === 'ضمة') return 'ُ';
  if (futureType === 'كسرة') return 'ِ';
  return 'َ';
}

